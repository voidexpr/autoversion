#!/usr/bin/env bash
# Build a tiny signed .app whose only job is to run one fixed command and wait
# for it. Grant Full Disk Access to the .app once: the program it starts
# inherits it. The program can be edited or rebuilt freely; only changing the
# command itself (path or fixed args) rebuilds the app and needs a new grant.
set -euo pipefail

function usage {
    cat <<EOF >&2
Usage: $(basename "$0") <dir/Name.app> <program> [fixed-args...]

Creates <dir/Name.app> running: <program> [fixed-args...] [args given to the app]
launchd should run <dir/Name.app>/Contents/MacOS/<Name> directly (not via open),
so it tracks the process (KeepAlive works), passes args and captures stdout/stderr.

Examples:
  $(basename "$0") ~/Applications/Minimon.app ~/bin/minimon
  $(basename "$0") ~/Applications/LaptopBackup.app /opt/homebrew/bin/bash ~/dotfiles/bin/backup-laptop.sh
EOF
    exit 1
}

[ $# -ge 2 ] || usage

APP=${1%/}
shift
NAME=$(basename "$APP" .app)
if [[ "$APP" != *.app || ! "$NAME" =~ ^[A-Za-z0-9._-]+$ ]]; then
    echo "error: first arg must be <dir>/<Name>.app (Name: letters, digits, . _ -)" >&2
    exit 1
fi
if [[ "$1" != /* ]]; then
    echo "error: program must be an absolute path: $1" >&2
    exit 1
fi
[ -x "$1" ] || echo "warning: $1 is not executable (yet)" >&2

SRC_REL="Contents/Resources/launcher.c"
EXE_REL="Contents/MacOS/$NAME"

function c-string {
    local s=${1//\\/\\\\}
    printf '"%s"' "${s//\"/\\\"}"
}

function launcher-source {
    echo "// Generated by make-fda-app.sh. Runs the command below and waits for it,"
    echo "// so the program inherits the Full Disk Access granted to this app."
    printf 'static const char *command[] = {'
    local arg
    for arg in "$@"; do printf ' %s,' "$(c-string "$arg")"; done
    echo ' 0 };'
    cat <<'EOF'

#include <errno.h>
#include <signal.h>
#include <spawn.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/wait.h>

extern char **environ;
static pid_t child;

static void forward(int sig) {
    kill(child, sig);
}

int main(int argc, char *argv[]) {
    size_t fixed = sizeof(command) / sizeof(command[0]) - 1;
    char **args = calloc(fixed + argc, sizeof(char *));
    if (!args) return 1;
    memcpy(args, command, fixed * sizeof(char *));
    // argv + 1 holds argc - 1 args plus the terminating NULL
    memcpy(args + fixed, argv + 1, argc * sizeof(char *));

    int err = posix_spawn(&child, args[0], NULL, NULL, args, environ);
    if (err) {
        fprintf(stderr, "%s: cannot run %s: %s\n", argv[0], args[0], strerror(err));
        return 127;
    }

    // Don't exec: this signed process must stay the parent for the grant to apply
    int sigs[] = {SIGHUP, SIGINT, SIGQUIT, SIGTERM, SIGUSR1, SIGUSR2};
    for (size_t i = 0; i < sizeof(sigs) / sizeof(sigs[0]); i++)
        signal(sigs[i], forward);

    int status;
    while (waitpid(child, &status, 0) < 0) {
        if (errno != EINTR) {
            perror("waitpid");
            return 1;
        }
    }
    if (WIFSIGNALED(status)) {
        signal(WTERMSIG(status), SIG_DFL);
        raise(WTERMSIG(status));
        return 128 + WTERMSIG(status);
    }
    return WEXITSTATUS(status);
}
EOF
}

NEW_SRC=$(launcher-source "$@")

if [ -e "$APP" ]; then
    if [ ! -f "$APP/$SRC_REL" ]; then
        echo "error: $APP exists and was not made by this script, move it away first" >&2
        exit 1
    fi
    if [ "$(cat "$APP/$SRC_REL")" = "$NEW_SRC" ] && codesign --verify --strict "$APP" 2>/dev/null; then
        echo "$APP is up to date, nothing to do"
        exit 0
    fi
fi

BUILD="$APP.new"
trap 'rm -rf "$BUILD"' EXIT
rm -rf "$BUILD"
mkdir -p "$BUILD/Contents/MacOS" "$BUILD/Contents/Resources"
echo "$NEW_SRC" > "$BUILD/$SRC_REL"

cat > "$BUILD/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleExecutable</key>
	<string>$NAME</string>
	<key>CFBundleIdentifier</key>
	<string>local.fda.$NAME</string>
	<key>CFBundleName</key>
	<string>$NAME</string>
	<key>CFBundlePackageType</key>
	<string>APPL</string>
	<key>CFBundleVersion</key>
	<string>1.0</string>
	<key>LSBackgroundOnly</key>
	<true/>
	<key>LSUIElement</key>
	<true/>
</dict>
</plist>
EOF

clang -O2 -Wall -Werror -o "$BUILD/$EXE_REL" "$BUILD/$SRC_REL"
codesign --force --sign - "$BUILD"

rm -rf "$APP"
mv "$BUILD" "$APP"
codesign --verify --strict "$APP"

echo "Built $APP, it runs: $*"
echo "launchd ProgramArguments[0]: $APP/$EXE_REL"
echo "Grant Full Disk Access: System Settings > Privacy & Security > Full Disk Access"
echo "  remove any old $NAME entry, then add $APP"
