package main

import (
	"flag"
	"os"
	"strings"
	"testing"

	"github.com/nicad/autoversion/filterrules"
)

// filtersDoc is the generated listing of the built-in groups
const filtersDoc = "filters/README.md"

var updateFiltersDoc = flag.Bool("update", false, "rewrite "+filtersDoc+" (make filter)")

// filtersDocText renders filters/README.md from the groups
func filtersDocText() string {
	var b strings.Builder
	b.WriteString(`# Built-in filter groups

Generated by ` + "`make filter`" + ` from the ` + "`*.filter`" + ` files in this folder: edit those, not
this file (` + "`go test`" + ` fails while it is stale).

Each file is a rules file in the filter syntax shared with ownit, see the
**filter** command in the main README. A filter adds a group with ` + "`use NAME`" + `,
or ` + "`--use NAME`" + ` on the command line. A group that combines others has only
` + "`use`" + ` lines: a tool reading these files directly resolves ` + "`use NAME`" + ` as
` + "`NAME.filter`" + ` in this folder, or runs ` + "`autoversion filter dump --use NAME`" + ` for
the group flat. File-name rules are typed (` + "`f:`" + `), so a folder named ` + "`x.old`" + `
or ` + "`x.mp3`" + ` is kept.

`)
	for _, g := range filterrules.Groups() {
		b.WriteString("## " + g.Name + ": " + g.About + "\n\n")
		b.WriteString("`use " + g.Name + "`, [" + g.Name + ".filter](" + g.Name + ".filter)\n\n```\n")
		for _, name := range g.Use {
			b.WriteString("use " + name + "\n")
		}
		for _, rule := range g.Exclude {
			b.WriteString("exclude " + rule + "\n")
		}
		b.WriteString("```\n\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// TestFiltersDoc keeps filters/README.md in step with the groups. It is the
// one test that writes outside a temp folder: only that file, only with
// -update (make filter).
func TestFiltersDoc(t *testing.T) {
	want := filtersDocText()
	if *updateFiltersDoc {
		if err := os.WriteFile(filtersDoc, []byte(want), 0644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(filtersDoc)
	if err != nil {
		t.Fatalf("%v: run make filter", err)
	}
	if string(got) != want {
		t.Errorf("%s is stale: run make filter", filtersDoc)
	}
}
